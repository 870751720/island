/** 拆开一封海神的信:消耗信纸并随机抽出一句留言,没有信返回 null */
export function openLetter(inventory: Inventory): string | null {
  if (!inventory.remove('letter', 1)) return null;
  return LETTER_MESSAGES[Math.floor(Math.random() * LETTER_MESSAGES.length)];
}
