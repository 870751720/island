/** 拔开一个漂流瓶:消耗瓶子并随机抽出一句留言,没有瓶子返回 null */
export function openBottle(inventory: Inventory): string | null {
  if (!inventory.remove('bottle', 1)) return null;
  return BOTTLE_MESSAGES[Math.floor(Math.random() * BOTTLE_MESSAGES.length)];
}
